// Build tabler/<category>.js packs from a Tabler Icons checkout: node scripts/build-tabler.mjs <path-to-tabler-icons>
// Each SVG carries a `category:` header comment; one ES module per category, outline icons only.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const root = process.argv[2];
if (!root) throw new Error('usage: build-tabler.mjs <path-to-tabler-icons>');
const SKIP = new Set(['Brand', 'Letters', 'Numbers', 'Zodiac', 'Gender']);
const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
const dir = join(root, 'icons/outline');
const packs = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
  const svg = readFileSync(join(dir, f), 'utf8');
  const cat = svg.match(/^category:\s*(.+)$/m)?.[1].trim();
  if (!cat || SKIP.has(cat)) continue;
  const inner = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s*\n\s*/g, '').replace(/ \/>/g, '/>');
  (packs[cat] ??= {})[f.slice(0, -4)] = inner;
}
mkdirSync('tabler', { recursive: true });
let total = 0;
for (const [cat, pack] of Object.entries(packs)) {
  const slug = cat.toLowerCase().replace(/[^a-z0-9]+/g, '-');
  const body = Object.entries(pack).map(([n, m]) => `  ${JSON.stringify(n)}: ${JSON.stringify(m)},`).join('\n');
  writeFileSync(`tabler/${slug}.js`, `// Tabler Icons ${version} (MIT, (c) Paweł Kuna), category "${cat}". Generated by scripts/build-tabler.mjs; see THIRD-PARTY-NOTICES.md.\nimport { registerTabler } from '../glyphs.js';\nexport const pack = {\n${body}\n};\nregisterTabler(pack);\n`);
  total += Object.keys(pack).length;
  console.log(slug.padEnd(16), String(Object.keys(pack).length).padStart(4));
}
console.log('total', total, 'tabler', version);
